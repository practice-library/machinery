// The plugin contract as a service: the calls, their request frames and their outcomes. Plan #17.
//
// A job's documents stay JSON Schema. Its input travels as a google.protobuf.Struct and its result as a
// google.protobuf.Value, each validated against the schema whose $id describe names, so one service serves
// every job and no job schema is written twice. Bounds and rules that proto cannot state are checked by the
// runtime, which answers INVALID_ARGUMENT: the caps ranges, the host pattern, exactly one of hosts and
// replay when network is given, network on RunUnit and Run, the replay start as 2026-10-31T12:00:00Z, and
// each recorded response's shape. A runtime's JSON decoder refuses unknown fields (connect-go's default
// codec discards them, so a Go runtime installs a strict one), so input sent to Describe is refused too.
//
// The JSON form follows proto's JSON mapping, which differs from contract v0 in ways a plain-JSON caller
// sees: the request names no contract and no verb (the call's path does); numbers in Struct and Value are
// doubles, exact up to 2^53 and written by every runtime as integers when they are; a decoder also accepts
// the proto field names (time_seconds) and integers written as strings.
//
// Outcomes: a call that succeeds returns its response with ok true. A call that fails returns a Connect
// error, never ok false in a success: FAILED_PRECONDITION (a valid request that fails, exit 1 of contract
// v0), RESOURCE_EXHAUSTED (an answer over output_bytes, exit 1), INVALID_ARGUMENT (not a valid request,
// exit 2), UNIMPLEMENTED (a package or call the plugin does not serve, exit 3), UNAVAILABLE (try again
// later, exit 75) and DEADLINE_EXCEEDED (over time_seconds).
//
// Every error the plugin itself returns has a message, which is its warnings joined with "; ", and carries
// one Failure detail. On the Connect JSON wire a detail is {"type": "machinery.plugin.v1alpha1.Failure",
// "value": <base64 of the binary message>}: typed clients decode it, and a plain-JSON caller reads code,
// message and each detail's type, which is plain JSON. An error without a Failure detail came from the
// transport or a proxy, not the plugin. A caller retries only UNAVAILABLE with a Failure detail; that is the
// plugin's "try again later" (exit 75 of contract v0).
//
// Unstable until v1, like contract v0: v1alpha1 may still change. From v1 on, buf breaking enforces
// additive-only change.

