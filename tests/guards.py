def main() -> int:
    failed = []
    skipped = 0
    for row in GUARDS:
        what, path, code, mutant, test = row[:5]
        needs = row[5] if len(row) > 5 else None
        if needs and sys.version_info < needs:
            print(f"skip {what}: needs Python {needs[0]}.{needs[1]}+ (CI runs it)")
            skipped += 1
            continue
        with tempfile.TemporaryDirectory() as tmp:
            for d in ("factrefresh", "tests", "conformance", "contract", "bin"):
                shutil.copytree(os.path.join(ROOT, d), os.path.join(tmp, d),
                                ignore=shutil.ignore_patterns("__pycache__"))
            target = os.path.join(tmp, path)
            with open(target, encoding="utf-8") as f:
                text = f.read()
            if text.count(code) != 1:
                failed.append(f"{what}: the guard's code occurs {text.count(code)} times in {path}")
                continue
            with open(target, "w", encoding="utf-8") as f:
                f.write(text.replace(code, mutant))
            out = subprocess.run([sys.executable, "-m", "unittest", test], cwd=tmp, capture_output=True, text=True)
            if out.returncode == 0:
                failed.append(f"{what}: {test} still passes without the guard")
            else:
                print(f"ok   {what}")
    for f in failed:
        print(f"FAIL {f}")
    print(f"{len(GUARDS) - len(failed) - skipped} of {len(GUARDS)} guards are tested"
          + (f"; {skipped} skipped on this Python" if skipped else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
